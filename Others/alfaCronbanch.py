# ======================================
# 2. Calcular Alfa de Cronbach
# ======================================
def cronbach_alpha(df):
    df_corr = df.corr()
    N = df.shape[1]  # número de ítems
    mean_r = df_corr.values[np.triu_indices(N, 1)].mean()
    alpha = (N * mean_r) / (1 + (N - 1) * mean_r)
    return alpha

alpha = cronbach_alpha(datos)
print("Alfa de Cronbach:", round(alpha, 3))

